def lean_rat(value: str) -> str:
    q = Fraction(value)
    if q.denominator == 1:
        return f"({q.numerator} : ℚ)"
    return f"({q.numerator} : ℚ) / {q.denominator}"


def wrapped_array(name: str, values: list[str], width: int = 92) -> str:
    lines = [f"def {name} : Array ℚ := #["]
    current = "  "
    for i, value in enumerate(values):
        token = value + ("," if i + 1 < len(values) else "")
        if len(current) > 2 and len(current) + len(token) + 1 > width:
            lines.append(current.rstrip())
            current = "  "
        current += token + " "
    if current.strip():
        lines.append(current.rstrip())
    lines.append("]")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()

    raw = args.source.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_ARCHIVE_SHA256:
        raise SystemExit(f"unexpected archive SHA-256: {digest}")
    data = json.loads(gzip.decompress(raw))
    continuum = data["continuum"]
    if continuum["source_coefficient_sha256"] != EXPECTED_COEFFICIENT_SHA256:
        raise SystemExit("unexpected coefficient SHA-256")
    if continuum["basis_degrees"] != list(range(0, 228, 2)):
        raise SystemExit("unexpected Laguerre basis")

    laguerre = [lean_rat(x) for x in continuum["laguerre_coefficients"]]
    power = [lean_rat(x) for x in continuum["power_coefficients_ascending"]]
    interval_values = [
        f"({lean_rat(left)}, {lean_rat(right)})" for left, right in INTERVALS
    ]

    generated = "\n\n".join(
        [
            "/- This file is generated by scripts/generate_certificate.py. -/\n"
            "import Mathlib.Data.Rat.Defs\n\n"
            "namespace UncertaintyUpperBound.CertificateData",
            wrapped_array("laguerreCoefficients", laguerre),
            wrapped_array("powerCoefficients", power),
            "def intervals : Array (ℚ × ℚ) := #[\n  "
            + ",\n  ".join(interval_values)
            + "\n]",
            'def archiveSHA256 : String := "' + EXPECTED_ARCHIVE_SHA256 + '"',
            'def coefficientSHA256 : String := "'
            + EXPECTED_COEFFICIENT_SHA256
            + '"',
            "end UncertaintyUpperBound.CertificateData\n",
        ]
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generated)


if __name__ == "__main__":
    main()
