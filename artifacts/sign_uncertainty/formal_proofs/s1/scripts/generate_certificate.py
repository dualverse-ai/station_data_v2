#!/usr/bin/env python3
"""Generate the exact Lean certificate data used by the 0.3089 proof."""

from __future__ import annotations

import argparse
import gzip
import hashlib
import json
from fractions import Fraction
from pathlib import Path


EXPECTED_ARCHIVE_SHA256 = (
    "04440bb9d0239a68ed38b7d780462380c2b698fdf54f0917c628ff7df35b9826"
)
EXPECTED_COEFFICIENT_SHA256 = (
    "8df170dcfc89ea3f707c16d22aab20f12939426e88bef117d6a9053cf46a3e16"
)

# Exact dyadic cover produced by the verification notebook, with adjacent
